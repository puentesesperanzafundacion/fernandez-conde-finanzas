create or replace function public.set_finance_record_trashed(
  p_entity text,
  p_id bigint,
  p_expected_updated_at timestamptz,
  p_trashed boolean
)
returns table (updated_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_current_updated_at timestamptz;
  v_status text;
  v_client_id bigint;
  v_concept text;
  v_amount_cents bigint;
  v_updated_at timestamptz;
begin
  if not public.is_finance_partner() then
    raise exception 'Tu cuenta no está autorizada para administrar la firma.';
  end if;

  if p_entity = 'client' then
    select clients.updated_at into v_current_updated_at
    from public.clients where clients.id = p_id for update;
    if not found then raise exception 'El cliente ya no existe.'; end if;
    if p_expected_updated_at is not null and v_current_updated_at <> p_expected_updated_at then
      raise exception 'Este cliente fue modificado por tu socio. Actualiza la información antes de continuar.';
    end if;
    if p_trashed and exists (
      select 1 from public.documents d where d.client_id = p_id and d.deleted_at is null
    ) then
      raise exception 'No puedes enviar este cliente a la papelera porque tiene documentos activos.';
    end if;
    update public.clients
    set deleted_at = case when p_trashed then now() else null end,
        deleted_by = case when p_trashed then auth.uid() else null end
    where clients.id = p_id
    returning clients.updated_at into v_updated_at;

  elsif p_entity = 'document' then
    select documents.updated_at, documents.status, documents.client_id, documents.concept, documents.amount_cents
    into v_current_updated_at, v_status, v_client_id, v_concept, v_amount_cents
    from public.documents where documents.id = p_id for update;
    if not found then raise exception 'El documento ya no existe.'; end if;
    if p_expected_updated_at is not null and v_current_updated_at <> p_expected_updated_at then
      raise exception 'Este documento fue modificado por tu socio. Actualiza la información antes de continuar.';
    end if;
    if not p_trashed and not exists (
      select 1 from public.clients c where c.id = v_client_id and c.deleted_at is null
    ) then
      raise exception 'Restaura primero al cliente relacionado con este documento.';
    end if;
    update public.documents
    set deleted_at = case when p_trashed then now() else null end,
        deleted_by = case when p_trashed then auth.uid() else null end
    where documents.id = p_id
    returning documents.updated_at into v_updated_at;

    if p_trashed then
      update public.movements
      set deleted_at = coalesce(deleted_at, now()),
          deleted_by = case when deleted_at is null then auth.uid() else deleted_by end
      where document_id = p_id and deleted_at is null;
    elsif v_status = 'Pagado' then
      insert into public.movements (type, category, description, amount_cents, document_id)
      values ('Ingreso', 'Honorarios', v_concept, v_amount_cents, p_id)
      on conflict (document_id) where document_id is not null
      do update set
        description = excluded.description,
        amount_cents = excluded.amount_cents,
        deleted_at = null,
        deleted_by = null;
    end if;

  elsif p_entity = 'movement' then
    select movements.updated_at into v_current_updated_at
    from public.movements
    where movements.id = p_id and movements.document_id is null
    for update;
    if not found then raise exception 'El gasto ya no existe o pertenece a un documento.'; end if;
    if p_expected_updated_at is not null and v_current_updated_at <> p_expected_updated_at then
      raise exception 'Este gasto fue modificado por tu socio. Actualiza la información antes de continuar.';
    end if;
    update public.movements
    set deleted_at = case when p_trashed then now() else null end,
        deleted_by = case when p_trashed then auth.uid() else null end
    where movements.id = p_id
    returning movements.updated_at into v_updated_at;
  else
    raise exception 'Tipo de registro no válido.';
  end if;

  return query select v_updated_at;
end;
$$;

