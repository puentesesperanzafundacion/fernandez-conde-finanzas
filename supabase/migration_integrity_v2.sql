create or replace function public.create_finance_document(
  p_kind text,
  p_client_id bigint,
  p_concept text,
  p_amount_cents bigint,
  p_status text,
  p_notes text,
  p_request_id uuid
)
returns table (id bigint, folio text, issued_at timestamptz, updated_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
  v_folio text;
  v_issued_at timestamptz;
  v_updated_at timestamptz;
  v_prefix text;
begin
  if not public.is_finance_partner() then
    raise exception 'Tu cuenta no está autorizada para administrar la firma.';
  end if;
  if p_request_id is null then
    raise exception 'Falta el identificador de la operación.';
  end if;
  if p_amount_cents < 0 then
    raise exception 'El importe no puede ser negativo.';
  end if;
  if not exists (select 1 from public.clients c where c.id = p_client_id and c.deleted_at is null) then
    raise exception 'El cliente ya no existe o se encuentra en la papelera.';
  end if;

  select d.id, d.folio, d.issued_at, d.updated_at
  into v_id, v_folio, v_issued_at, v_updated_at
  from public.documents d
  where d.client_request_id = p_request_id;

  if found then
    return query select v_id, v_folio, v_issued_at, v_updated_at;
    return;
  end if;

  v_prefix := case p_kind
    when 'Presupuesto' then 'PRE'
    when 'Recibo' then 'REC'
    when 'Cuenta de cobro' then 'COB'
    else null
  end;
  if v_prefix is null then
    raise exception 'Tipo de documento no válido.';
  end if;

  v_id := nextval(pg_get_serial_sequence('public.documents', 'id'));
  v_folio := v_prefix || '-' || lpad(v_id::text, 4, '0');

  insert into public.documents (
    id, folio, kind, client_id, concept, amount_cents, status, notes, client_request_id
  ) values (
    v_id, v_folio, p_kind, p_client_id, trim(p_concept), p_amount_cents,
    p_status, coalesce(p_notes, ''), p_request_id
  )
  on conflict (client_request_id) do nothing
  returning documents.issued_at, documents.updated_at
  into v_issued_at, v_updated_at;

  if not found then
    select d.id, d.folio, d.issued_at, d.updated_at
    into v_id, v_folio, v_issued_at, v_updated_at
    from public.documents d
    where d.client_request_id = p_request_id;
    return query select v_id, v_folio, v_issued_at, v_updated_at;
    return;
  end if;

  if p_status = 'Pagado' then
    insert into public.movements (
      type, category, description, amount_cents, document_id
    ) values (
      'Ingreso', 'Honorarios', trim(p_concept), p_amount_cents, v_id
    );
  end if;

  return query select v_id, v_folio, v_issued_at, v_updated_at;
end;
$$;

create or replace function public.update_finance_document(
  p_id bigint,
  p_kind text,
  p_client_id bigint,
  p_concept text,
  p_amount_cents bigint,
  p_status text,
  p_notes text,
  p_expected_updated_at timestamptz
)
returns table (updated_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_document public.documents%rowtype;
  v_updated_at timestamptz;
begin
  if not public.is_finance_partner() then
    raise exception 'Tu cuenta no está autorizada para administrar la firma.';
  end if;
  select * into v_document from public.documents
  where documents.id = p_id and deleted_at is null
  for update;
  if not found then
    raise exception 'Este documento ya no existe o fue enviado a la papelera.';
  end if;
  if p_expected_updated_at is not null and v_document.updated_at <> p_expected_updated_at then
    raise exception 'Este documento fue modificado por tu socio. Actualiza la información antes de volver a editarlo.';
  end if;
  if not exists (select 1 from public.clients c where c.id = p_client_id and c.deleted_at is null) then
    raise exception 'El cliente ya no existe o se encuentra en la papelera.';
  end if;

  update public.documents
  set kind = p_kind,
      client_id = p_client_id,
      concept = trim(p_concept),
      amount_cents = p_amount_cents,
      status = p_status,
      notes = coalesce(p_notes, '')
  where documents.id = p_id
  returning documents.updated_at into v_updated_at;

  if p_status = 'Pagado' then
    insert into public.movements (
      type, category, description, amount_cents, document_id
    ) values (
      'Ingreso', 'Honorarios', trim(p_concept), p_amount_cents, p_id
    )
    on conflict (document_id) where document_id is not null
    do update set
      description = excluded.description,
      amount_cents = excluded.amount_cents,
      deleted_at = null,
      deleted_by = null;
  else
    update public.movements
    set deleted_at = coalesce(deleted_at, now()),
        deleted_by = case when deleted_at is null then auth.uid() else deleted_by end
    where document_id = p_id and deleted_at is null;
  end if;

  return query select v_updated_at;
end;
$$;

