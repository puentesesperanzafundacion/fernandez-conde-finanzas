create or replace function public.touch_finance_record()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  if old.deleted_at is null and new.deleted_at is not null then
    new.deleted_by := auth.uid();
  elsif old.deleted_at is not null and new.deleted_at is null then
    new.deleted_by := null;
  end if;
  return new;
end;
$$;

create or replace function public.log_finance_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_entity text;
  v_action text;
begin
  v_entity := case tg_table_name
    when 'clients' then 'client'
    when 'documents' then 'document'
    else 'movement'
  end;

  if tg_op = 'INSERT' then
    v_action := 'created';
  elsif old.deleted_at is null and new.deleted_at is not null then
    v_action := 'trashed';
  elsif old.deleted_at is not null and new.deleted_at is null then
    v_action := 'restored';
  else
    v_action := 'updated';
  end if;

  insert into public.finance_audit_log (entity, record_id, action, actor_id, snapshot)
  values (v_entity, new.id, v_action, auth.uid(), to_jsonb(new));
  return new;
end;
$$;

